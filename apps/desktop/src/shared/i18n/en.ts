type WritableDeep<T> = T extends string ? string : { -readonly [K in keyof T]: WritableDeep<T[K]> };

type DotPath<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string ? `${P}${K}` : DotPath<T[K], `${P}${K}.`>;
}[keyof T & string];

